"""Generate site/events.js from data/events.yaml + data/sources.yaml.

Tags = topics of the event's series (sources.yaml) + optional per-event `tags`
(events.yaml). Topics of aggregator / mailing-list / social sources are only
inherited when the event has neither its own `tags` nor a conference_series
(they are too broad).
Format = event `format` (in-person | online | hybrid), else "not stated".
Region = event `region` (string or list) if given, else guessed from `location`.
Link   = event `url`, else the first http(s) URL in `source`.
Usage: python3 scripts/build_site.py
"""
import json
import re
from datetime import date
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
events = yaml.safe_load((ROOT / "data/events.yaml").read_text())
sources = {s["id"]: s for s in yaml.safe_load((ROOT / "data/sources.yaml").read_text())}

# Keyword -> region. Checked in order; an event can match several (distributed meetings).
REGIONS = [
    ("Middle East & Africa", r"UAE|Abu Dhabi|Egypt|South Africa|Israel|Turkey|Nigeria|Kenya|Morocco"),
    ("Latin America", r"Brazil|Chile|Argentina|Mexico|Colombia|Peru|Uruguay|Rio de Janeiro|Santiago|Sergipe"),
    ("Asia", r"Japan|Tokyo|Fukuoka|Kyoto|Korea|Seoul|China|Shanghai|Beijing|Hong Kong|Taiwan|\bIndia\b|Singapore"),
    ("Oceania", r"Australia|New Zealand|\bNZ\b|Wellington|Sydney|Melbourne|Surfers Paradise"),
    ("North America", r"\b(MD|NY|IN|IL|CA|WI|DC|VA|GA|CT|MA|TX|FL|CO)\b|United States|USA|Canada|Montr[ée]al|"
                      r"Toronto|Hamilton|Colorado|Florida|Texas|Baltimore|Boston|Yale|Hofstra|Virginia|Bard College"),
    ("Europe", r"\bUK\b|United Kingdom|London|Manchester|Durham|Oxford|Cambridge, UK|Edinburgh|Belfast|Dublin|"
               r"Ireland|France|Paris|Bordeaux|Germany|Berlin|Hamburg|Jena|W[üu]rzburg|Bielefeld|Italy|Rome|"
               r"Cremona|L'Aquila|Spain|Barcelona|Portugal|Coimbra|Austria|Vienna|Belgium|Brussels|Croatia|"
               r"Zagreb|Slovenia|Ljubljana|Serbia|Belgrade|Bulgaria|Plovdiv|Greece|Thessaloniki|Finland|"
               r"Helsinki|Norway|Stavanger|Netherlands|Amsterdam|Czech|Brno|Sweden|Denmark|Switzerland|Poland|"
               r"Lithuania|Vilnius|Latvia|Estonia|"
               r"King's College"),
]


def regions_of(e):
    if e.get("region"):
        r = e["region"]
        return r if isinstance(r, list) else [r]
    loc = e.get("location") or ""
    found = [name for name, pat in REGIONS if re.search(pat, loc)]
    if not found and re.search(r"online", loc, re.I):
        return ["Online only"]
    if not found and e.get("format") == "online":
        return ["Online only"]
    return found or ["Not stated"]


def link_of(e):
    if e.get("url"):
        return e["url"]
    m = re.search(r"https?://\S+", e.get("source") or "")
    return m.group(0) if m else None


out, unmatched = [], []
for e in events:
    has_series = any(sources.get(s, {}).get("kind") == "conference_series" for s in e.get("series", []))
    tags = []
    for sid in e.get("series", []):
        src = sources.get(sid, {})
        if (e.get("tags") or has_series) and src.get("kind") != "conference_series":
            continue
        tags += src.get("topics", [])
    tags += e.get("tags", [])
    regions = regions_of(e)
    if regions == ["Not stated"] and e.get("location"):
        unmatched.append(e["location"])
    out.append({
        "id": e["id"],
        "name": e["name"],
        "series": [sources[s]["name"] for s in e.get("series", [])
                   if s in sources and sources[s]["kind"] == "conference_series"],
        "via": [sources[s].get("short", sources[s]["name"]) for s in e.get("series", [])
                if s in sources and sources[s]["kind"] != "conference_series"],
        "start": e.get("start"), "end": e.get("end"),
        "location": e.get("location"),
        "format": e.get("format") or "not stated",
        "regions": regions,
        "url": link_of(e),
        "deadlines": [d for d in e.get("deadlines", []) if d.get("date")],
        "status": e.get("status"),
        "verified": bool(e.get("verified")),
        "tags": sorted(set(tags)),
    })

js = (f"// Generated by scripts/build_site.py on {date.today().isoformat()}. Do not edit.\n"
      f"window.EVENTS = {json.dumps(out, ensure_ascii=False, indent=1)};\n"
      f"window.GENERATED = {json.dumps(date.today().isoformat())};\n")
(ROOT / "site/events.js").write_text(js)
print(f"site/events.js: {len(out)} events, {len({t for e in out for t in e['tags']})} distinct tags")
if unmatched:
    print("WARNING: no region matched for locations:", sorted(set(unmatched)))
